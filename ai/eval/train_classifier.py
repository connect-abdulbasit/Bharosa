"""Dev-only: train the text model with scikit-learn and export it as pure-Python constants (bharosa_ai/classify_ml_weights.py).

Needs scikit-learn (`pip install "./ai[ml]"`). Model: TfidfVectorizer(char_wb 2-4-grams, min_df=2, max_features=4000, sublinear_tf) ->
LogisticRegression -> CalibratedClassifierCV(method="sigmoid", cv=3, ensemble=False): "scam" versus everything else, trained on ALL
150 synthetic messages. Run again whenever data/cases.py changes. The exported file has no scikit-learn dependency; bharosa_ai/
classify_ml.py scores with it, and tests/test_classify_ml.py checks parity against scikit-learn.

Run:  python ai/eval/train_classifier.py
"""
import importlib.util
import sys
from pathlib import Path
from typing import Any, Dict, List, Tuple

HERE = Path(__file__).resolve().parent
AI_DIR = HERE.parent
for _p in (str(AI_DIR.parent), str(AI_DIR)):
    if _p not in sys.path:
        sys.path.insert(0, _p)

from bharosa_ai import classify_ml  # noqa: E402

WEIGHTS_PATH = AI_DIR / "bharosa_ai" / "classify_ml_weights.py"


def _messages() -> List[tuple]:
    spec = importlib.util.spec_from_file_location("cases_for_training", AI_DIR / "data" / "cases.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.MESSAGES


def make_model() -> Tuple[Any, Any]:
    from sklearn.calibration import CalibratedClassifierCV
    from sklearn.feature_extraction.text import TfidfVectorizer
    from sklearn.linear_model import LogisticRegression

    vectorizer = TfidfVectorizer(analyzer="char_wb", ngram_range=(2, 4), min_df=2, max_features=4000, sublinear_tf=True)
    classifier = CalibratedClassifierCV(LogisticRegression(C=10, max_iter=2000, class_weight="balanced"), method="sigmoid", cv=3,
                                        ensemble=False)
    return vectorizer, classifier


def train() -> Dict[str, Any]:
    rows = _messages()
    docs = [classify_ml.make_doc(t, s) for t, s, *_ in rows]
    y = [1 if r[2] == "scam" else 0 for r in rows]
    vectorizer, classifier = make_model()
    x = vectorizer.fit_transform(docs)
    classifier.fit(x, y)
    fitted = classifier.calibrated_classifiers_[0]
    lr, calibrator = fitted.estimator, fitted.calibrators[0]
    features = {g: (float(vectorizer.idf_[i]), float(lr.coef_[0][i])) for g, i in vectorizer.vocabulary_.items()}
    return {"features": features, "intercept": float(lr.intercept_[0]), "cal_a": float(calibrator.a_), "cal_b": float(calibrator.b_),
            "trained_on": len(rows), "vectorizer": vectorizer, "classifier": classifier, "x": x}


def write_weights(model: Dict[str, Any], path: Path = WEIGHTS_PATH) -> None:
    lines = ['"""GENERATED by ai/eval/train_classifier.py from scikit-learn. Do not edit by hand: run the script again.',
             "",
             "Weights of the scam text model (see classify_ml.py). TF-IDF idf and logistic-regression coefficient per character n-gram,",
             "the intercept, and the sigmoid calibration (p = 1 / (1 + exp(CAL_A * z + CAL_B))). Trained on %d synthetic messages." % model["trained_on"],
             '"""',
             "TRAINED_ON = %d" % model["trained_on"], "INTERCEPT = %r" % model["intercept"], "CAL_A = %r" % model["cal_a"],
             "CAL_B = %r" % model["cal_b"], "", "FEATURES = {"]
    for gram in sorted(model["features"]):
        idf, coef = model["features"][gram]
        lines.append("    %r: (%r, %r)," % (gram, idf, coef))
    lines.append("}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    try:
        model = train()
    except ImportError:
        print('scikit-learn is not installed: pip install "./ai[ml]"')
        return 2
    write_weights(model)
    print("wrote %s: %d features, trained on %d messages" % (WEIGHTS_PATH, len(model["features"]), model["trained_on"]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
